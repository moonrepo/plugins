// Yarn's commands differ by major: 1 (classic), 2 to 4 (Berry) and 6 (zpm)

use moon_pdk_api::{AnyResult, UnresolvedVersionSpec, VirtualPath};
use starbase_utils::fs;

/// Yarn's major version, from the configured `version`, or else the root's
/// `yarn.lock`, as each major writes its own format. Berry's is 4, and no
/// lockfile is 1.
pub fn detect_yarn_major(
    version: Option<&UnresolvedVersionSpec>,
    root: &VirtualPath,
) -> AnyResult<u32> {
    match version {
        Some(UnresolvedVersionSpec::Version(version)) => return Ok(version.major),
        Some(UnresolvedVersionSpec::Requirement(req)) => {
            if let Some(major) = req.major {
                return Ok(major);
            }
        }
        Some(UnresolvedVersionSpec::Canary) => return Ok(6),
        // As node_depman_tool resolves them
        Some(UnresolvedVersionSpec::Alias(alias)) => {
            return Ok(match alias.as_str() {
                "rust" | "zpm" => 6,
                "classic" | "legacy" => 1,
                _ => 4,
            });
        }
        _ => {}
    };

    let lock_path = root.join("yarn.lock");

    if lock_path.exists() {
        let content = fs::read_file(lock_path)?;

        if content.trim_start().starts_with('{') {
            return Ok(6);
        }

        if content.lines().any(|line| line.starts_with("__metadata:")) {
            return Ok(4);
        }
    }

    Ok(1)
}

#[cfg(test)]
mod tests {
    use super::*;
    use starbase_sandbox::create_empty_sandbox;

    fn detect(version: Option<&str>, lockfile: Option<&str>) -> u32 {
        let sandbox = create_empty_sandbox();

        if let Some(content) = lockfile {
            sandbox.create_file("yarn.lock", content);
        }

        detect_yarn_major(
            version
                .map(|version| UnresolvedVersionSpec::parse(version).unwrap())
                .as_ref(),
            &VirtualPath::new(sandbox.path()),
        )
        .unwrap()
    }

    #[test]
    fn detects_from_the_version() {
        assert_eq!(detect(Some("1.22.22"), None), 1);
        assert_eq!(detect(Some("4.18.1"), None), 4);
        assert_eq!(detect(Some("6.0.0-rc.23"), None), 6);
        assert_eq!(detect(Some("~3.6"), None), 3);
        assert_eq!(detect(Some("^6.0.0-rc.0"), None), 6);
    }

    #[test]
    fn detects_from_aliases() {
        assert_eq!(detect(Some("canary"), None), 6);
        assert_eq!(detect(Some("rust"), None), 6);
        assert_eq!(detect(Some("zpm"), None), 6);
        assert_eq!(detect(Some("classic"), None), 1);
        assert_eq!(detect(Some("legacy"), None), 1);
        assert_eq!(detect(Some("latest"), None), 4);
        assert_eq!(detect(Some("berry"), None), 4);
        assert_eq!(detect(Some("stable"), None), 4);
    }

    #[test]
    fn detects_from_the_lockfile() {
        let classic = "# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n";
        let berry = "# This file is generated by running \"yarn install\" inside your project.\n\n__metadata:\n  version: 8\n";
        let zpm = r#"{"__metadata":{"version":10},"entries":{}}"#;

        assert_eq!(detect(None, None), 1);
        assert_eq!(detect(None, Some("")), 1);
        assert_eq!(detect(None, Some(classic)), 1);
        assert_eq!(detect(None, Some(berry)), 4);
        assert_eq!(detect(None, Some(zpm)), 6);

        // Ranges and wildcards don't name a major
        assert_eq!(detect(Some(">=2 <5"), Some(berry)), 4);
        assert_eq!(detect(Some("*"), Some(zpm)), 6);
    }
}
