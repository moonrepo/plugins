// `requirements.txt` and `requirements.in`, in pip's format:
// https://pip.pypa.io/en/stable/reference/requirements-file-format/

/// A requirement line, without its options or comment.
#[derive(Debug, Default, PartialEq)]
pub struct RequirementLine {
    pub requirement: String,
    /// The first `--hash=sha256:<hex>`, as bare hex.
    pub hash: Option<String>,
}

/// Split a requirements file into requirement lines, following pip's rules. Lines
/// for options, like `-r`, `-c`, `-e` and `--index-url`, are skipped, as included
/// files aren't followed.
pub fn parse_requirements_file(content: &str) -> Vec<RequirementLine> {
    join_lines(content)
        .into_iter()
        .filter_map(|line| {
            let line = strip_comment(&line).trim();

            if line.is_empty() || line.starts_with('-') {
                return None;
            }

            Some(split_options(line))
        })
        .collect()
}

fn is_comment_line(line: &str) -> bool {
    line.trim_start().starts_with('#')
}

/// Join a line ending in `\` with the next, like pip's `join_lines`.
/// A comment line never continues.
fn join_lines(content: &str) -> Vec<String> {
    let mut lines = vec![];
    let mut current = String::new();
    let mut continuing = false;

    for line in content.lines() {
        if let Some(head) = line.strip_suffix('\\')
            && !is_comment_line(line)
        {
            current.push_str(head);
            continuing = true;

            continue;
        }

        if continuing {
            // So that a trailing comment is still stripped
            if is_comment_line(line) {
                current.push(' ');
            }

            current.push_str(line);
            lines.push(std::mem::take(&mut current));
            continuing = false;
        } else {
            lines.push(line.to_owned());
        }
    }

    if continuing {
        lines.push(current);
    }

    lines
}

/// Strip a comment, which is `#` at the start of a line or after whitespace,
/// so URL fragments like `#egg=name` are kept.
fn strip_comment(line: &str) -> &str {
    let mut prev_is_whitespace = true;

    for (index, ch) in line.char_indices() {
        if ch == '#' && prev_is_whitespace {
            return &line[..index];
        }

        prev_is_whitespace = ch.is_whitespace();
    }

    line
}

/// Split the requirement from its options, which start at the first
/// argument that starts with `-`, like pip's `break_args_options`.
fn split_options(line: &str) -> RequirementLine {
    let mut requirement = vec![];
    let mut options = vec![];

    for token in line.split_whitespace() {
        if !options.is_empty() || token.starts_with('-') {
            options.push(token);
        } else {
            requirement.push(token);
        }
    }

    let mut hash = None;
    let mut tokens = options.into_iter();

    while let Some(token) = tokens.next() {
        let value = match token.strip_prefix("--hash") {
            Some(rest) if rest.starts_with('=') => Some(&rest[1..]),
            Some("") => tokens.next(),
            _ => None,
        };

        if let Some(hex) = value.and_then(|value| value.strip_prefix("sha256:")) {
            hash = Some(hex.to_owned());
            break;
        }
    }

    RequirementLine {
        requirement: requirement.join(" "),
        hash,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn requirement(value: &str) -> RequirementLine {
        RequirementLine {
            requirement: value.into(),
            hash: None,
        }
    }

    fn hashed(value: &str, hash: &str) -> RequirementLine {
        RequirementLine {
            requirement: value.into(),
            hash: Some(hash.into()),
        }
    }

    #[test]
    fn parses_uv_export_output() {
        let content = r#"# This file was autogenerated by uv via the following command:
#    uv export --frozen
idna==3.10 \
    --hash=sha256:12f65c9b470abda6dc35cf8e63cc574b1c52b11df2c86030af0ac09b01b13ea9 \
    --hash=sha256:946d195a0d259cbba61165e88e65941f16e9b36ea6ddb97f00452bae8b1287d3
    # via requests
six==1.17.0 ; python_full_version >= '3.12' \
    --hash=sha256:4721f391ed90541fddacab5acf947aa0d3dc7d27b2e1e8eda2be8970586c3274
"#;

        assert_eq!(
            parse_requirements_file(content),
            [
                hashed(
                    "idna==3.10",
                    "12f65c9b470abda6dc35cf8e63cc574b1c52b11df2c86030af0ac09b01b13ea9"
                ),
                hashed(
                    "six==1.17.0 ; python_full_version >= '3.12'",
                    "4721f391ed90541fddacab5acf947aa0d3dc7d27b2e1e8eda2be8970586c3274"
                ),
            ]
        );
    }

    #[test]
    fn strips_pip_compile_annotations() {
        let content = "certifi==2025.1.31  # via requests\n# via -r requirements.in\nrequests==2.32.3\n    # via -r requirements.in\n";

        assert_eq!(
            parse_requirements_file(content),
            [
                requirement("certifi==2025.1.31"),
                requirement("requests==2.32.3")
            ]
        );
    }

    #[test]
    fn skips_option_lines() {
        let content = "--index-url https://example.com/simple\n-r base.txt\n-c constraints.txt\n-e ../lib\n--no-binary :all:\nsix\n";

        assert_eq!(parse_requirements_file(content), [requirement("six")]);
    }

    #[test]
    fn keeps_url_fragments() {
        assert_eq!(
            parse_requirements_file("pkg @ https://example.com/pkg.zip#egg=pkg\n"),
            [requirement("pkg @ https://example.com/pkg.zip#egg=pkg")]
        );
    }

    #[test]
    fn supports_spaced_hash_options() {
        assert_eq!(
            parse_requirements_file("six==1.17.0 --hash sha256:abc --hash=sha512:def\n"),
            [hashed("six==1.17.0", "abc")]
        );
        assert_eq!(
            parse_requirements_file("six==1.17.0 --hash=sha512:def --hash=sha256:abc\n"),
            [hashed("six==1.17.0", "abc")]
        );
    }

    #[test]
    fn doesnt_continue_comment_lines() {
        assert_eq!(
            parse_requirements_file("# a comment \\\nsix\n"),
            [requirement("six")]
        );
    }

    #[test]
    fn handles_a_trailing_continuation() {
        assert_eq!(parse_requirements_file("six \\"), [requirement("six")]);
    }
}
